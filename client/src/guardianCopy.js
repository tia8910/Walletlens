export const GUARDIAN_COPY = { en, ar, fr, es, de, it }

/** The copy for a language, falling back to English key by key. */
export function guardianCopy(lang) {
  const pack = GUARDIAN_COPY[lang] || en
  return (key) => (key in pack ? pack[key] : en[key])
}
